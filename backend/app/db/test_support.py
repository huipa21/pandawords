"""Isolated test database lifecycle; never select the development database."""

from __future__ import annotations

import re
from collections.abc import AsyncIterator
from contextlib import asynccontextmanager
from pathlib import Path
from urllib.parse import urlsplit
from uuid import uuid4

from surrealdb.connections.async_ws import AsyncWsSurrealConnection

from app.core.config import Settings
from app.db.migrate import run_migrations
from app.db.migration_store import checked_query
from app.db.migration_test_support import remove_database


def _validate_test_server(settings: Settings) -> None:
    url = urlsplit(settings.surreal_test_url)
    if url.hostname not in {"localhost", "127.0.0.1", "::1"} or url.port != 8101:
        raise ValueError("The test harness requires the loopback test server on port 8101")


def test_database_settings() -> Settings:
    settings = Settings()
    _validate_test_server(settings)
    root = Path(__file__).resolve().parents[3]
    short = re.sub(r"[^a-z0-9]+", "_", root.name.lower()).strip("_")[:24] or "worktree"
    return settings.model_copy(
        update={
            "surreal_url": settings.surreal_test_url,
            "surreal_namespace": "pandawords_test",
            "surreal_database": f"t_{short}_{uuid4().hex[:8]}",
        }
    )


@asynccontextmanager
async def isolated_database(
    settings: Settings, *, migrate: bool
) -> AsyncIterator[AsyncWsSurrealConnection]:
    _validate_test_server(settings)
    if settings.surreal_namespace != "pandawords_test" or not re.fullmatch(
        r"t_[a-z0-9_]+_[0-9a-f]{8}", settings.surreal_database
    ):
        raise ValueError("Refusing to manage a database not generated by the test harness")
    if settings.surreal_url != settings.surreal_test_url:
        raise ValueError("Refusing to connect the test harness to a non-test URL")
    async with AsyncWsSurrealConnection(
        settings.surreal_url, timeout=settings.surreal_timeout_seconds
    ) as connection:
        await connection.signin(
            {"username": settings.surreal_user, "password": settings.surreal_pass}
        )
        await connection.use(settings.surreal_namespace, settings.surreal_database)
        try:
            if migrate:
                await run_migrations(connection)
            yield connection
        finally:
            await remove_database(connection, settings.surreal_database)


async def write_probe(connection: AsyncWsSurrealConnection, value: str) -> None:
    await checked_query(
        connection,
        "DEFINE TABLE IF NOT EXISTS migration_probe SCHEMAFULL; "
        "DEFINE FIELD IF NOT EXISTS value ON migration_probe TYPE string; "
        "UPSERT migration_probe:row SET value = $value;",
        {"value": value},
    )


async def database_names(connection: AsyncWsSurrealConnection) -> set[str]:
    return set((await checked_query(connection, "INFO FOR NS;"))[0]["databases"])
